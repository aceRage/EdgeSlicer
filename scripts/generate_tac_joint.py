#!/usr/bin/env python3
"""Reproduce the embedded TAC Joint data from the unmodified binary STL references.

Uses only the Python standard library. --check verifies tracked generated files
without writing. Source assets are deliberately retained byte-for-byte.
"""
import argparse
import collections
import hashlib
import json
import math
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "resources/cut_connectors/tac_joint"
OUTPUT = ROOT / "src/libslic3r/TacJointData.inc"


def sub(a, b):
    return tuple(x - y for x, y in zip(a, b))


def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def unit(a):
    length = math.sqrt(dot(a, a))
    return tuple(x / length for x in a)


def read_stl(path):
    data = path.read_bytes()
    count = struct.unpack_from("<I", data, 80)[0]
    if len(data) != 84 + 50 * count:
        raise ValueError(f"Not a binary STL: {path}")
    vertices, indices, lookup = [], [], {}
    for i in range(count):
        values = struct.unpack_from("<12fH", data, 84 + 50 * i)
        triangle = []
        for j in (3, 6, 9):
            vertex = values[j:j + 3]
            if vertex not in lookup:
                lookup[vertex] = len(vertices)
                vertices.append(vertex)
            triangle.append(lookup[vertex])
        indices.append(tuple(triangle))
    edges = collections.Counter(tuple(sorted((a, b))) for t in indices for a, b in zip(t, t[1:] + t[:1]))
    if any(count != 2 for count in edges.values()):
        raise ValueError(f"Reference is not closed: {path}")
    return vertices, indices, hashlib.sha256(data).hexdigest()


def frame(vertices, indices):
    # Select the largest triangles with normals nearest original +X and +Z.
    # Both define large planar faces, rather than unstable principal axes of
    # the asymmetric shape. Gram-Schmidt removes STL float quantization noise.
    normals = [cross(sub(vertices[t[1]], vertices[t[0]]), sub(vertices[t[2]], vertices[t[0]])) for t in indices]
    x = unit(max((n for n in normals if unit(n)[0] > .99), key=lambda n: dot(n, n)))
    top = unit(max((n for n in normals if unit(n)[2] > .99), key=lambda n: dot(n, n)))
    z = unit(cross(top, x))
    y = unit(cross(z, x))
    rotation = (x, y, z)
    aligned = [tuple(dot(row, v) for row in rotation) for v in vertices]
    centre = tuple((min(v[i] for v in aligned) + max(v[i] for v in aligned)) / 2 for i in range(3))
    return rotation, tuple(-c for c in centre)


def number(value, single=False):
    result = format(value, ".9g" if single else ".17g")
    if "." not in result and "e" not in result:
        result += ".0"
    return result + ("f" if single else "")


def generate():
    connector = read_stl(ASSETS / "connector.stl")
    cutter = read_stl(ASSETS / "connector cutter.stl")
    rotation, translation = frame(*connector[:2])
    lines = ["// Generated by scripts/generate_tac_joint.py. Do not edit.",
             "// Original STL coordinates; the same rigid transform is applied to both meshes."]
    lines.append("static const double TAC_ROTATION[3][3] = {")
    lines.extend("    {" + ", ".join(number(x) for x in row) + "}," for row in rotation)
    lines.append("};")
    lines.append("static const double TAC_TRANSLATION[3] = {" + ", ".join(number(x) for x in translation) + "};")
    metadata = {"version": 1, "units": "mm", "source_to_connector_rotation": rotation,
                "source_to_connector_translation": translation, "meshes": {}}
    for name, mesh in (("CONNECTOR", connector), ("CUTTER", cutter)):
        vertices, indices, digest = mesh
        lines.append(f"static const float TAC_{name}_VERTICES[][3] = {{")
        lines.extend("    {" + ", ".join(number(x, True) for x in v) + "}," for v in vertices)
        lines.append("};")
        lines.append(f"static const int TAC_{name}_INDICES[][3] = {{")
        lines.extend("    {" + ", ".join(str(x) for x in t) + "}," for t in indices)
        lines.append("};")
        transformed = [tuple(dot(row, v) + translation[i] for i, row in enumerate(rotation)) for v in vertices]
        metadata["meshes"][name.lower()] = {"sha256": digest, "vertices": len(vertices), "triangles": len(indices),
            "dimensions_mm": [max(v[i] for v in transformed) - min(v[i] for v in transformed) for i in range(3)]}
    return {OUTPUT: "\n".join(lines) + "\n", ASSETS / "reference.json": json.dumps(metadata, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, contents in generate().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != contents:
                raise SystemExit(f"Stale generated TAC Joint data: {path}")
        else:
            path.write_text(contents, encoding="utf-8", newline="\n")
        print(f"{'Verified' if args.check else 'Generated'} {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
