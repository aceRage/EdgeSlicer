// Two filaments on one 0.4 nozzle (an AMS-style single tool), no tower unless asked.
DynamicPrintConfig two_filaments(bool tower)
{
    DynamicPrintConfig config = DynamicPrintConfig::full_print_config();
    config.set_num_extruders(2);
    config.set_num_filaments(2);
    config.set_deserialize_strict({
        { "nozzle_diameter", "0.4,0.4" },
        { "filament_diameter", "1.75,1.75" },
        { "single_extruder_multi_material", "1" },
        { "enable_prime_tower", tower ? "1" : "0" },
        { "enable_support", "0" },
        { "sparse_infill_density", "15%" },
        { "layer_height", "0.3" },
        { "initial_layer_print_height", "0.3" },
        { "top_shell_layers", "3" },
        { "bottom_shell_layers", "3" },
        { "wall_loops", "2" },
        { "skirt_loops", "0" },
        { "brim_type", "no_brim" },
        { "gcode_comments", "1" },
        // Inside the default bed, clear of the arranged cube (as test_wipe_tower.cpp places it).
        { "wipe_tower_x", "15" },
        { "wipe_tower_y", "120" },
        { "prime_tower_width", "35" },
        { "prime_tower_brim_width", "0" },
    });
    return config;
}

// Per extruding XY move: the ";TYPE:" and the "T<n>" in force (-1 before the first tool change).
struct Move
{
    std::string type;
    int         tool;
};

std::vector<Move> moves_of(const std::string &gcode)
{
    std::vector<Move>  out;
    std::istringstream in(gcode);
    std::string        line, type;
    int                tool = -1;
    while (std::getline(in, line)) {
        if (!line.empty() && line.back() == '\r')
            line.pop_back();
        if (line.rfind(";TYPE:", 0) == 0)
            type = line.substr(6);
        else if (line.size() > 1 && line[0] == 'T' && std::isdigit(static_cast<unsigned char>(line[1])))
            tool = std::atoi(line.c_str() + 1);
        else if (line.rfind("G1 ", 0) == 0 || line.rfind("G2 ", 0) == 0 || line.rfind("G3 ", 0) == 0) {
            const std::string body = line.substr(0, line.find(';'));
            const size_t      e    = body.find(" E");
            const bool        xy   = body.find(" X") != std::string::npos || body.find(" Y") != std::string::npos;
            if (xy && e != std::string::npos && std::atof(body.c_str() + e + 2) > 0.)
                out.push_back({ type, tool });
        }
    }
    return out;
}

// The tools a feature prints with; -1 (before any tool change) counts as the first filament, T0.
std::set<int> tools_of(const std::vector<Move> &moves, const std::string &type)
{
    std::set<int> out;
    for (const Move &m : moves)
        if (m.type == type)
            out.insert(std::max(m.tool, 0));
    return out;
}

// The features printed with `tool`.
std::set<std::string> types_on(const std::vector<Move> &moves, int tool)
{
    std::set<std::string> out;
    for (const Move &m : moves)
        if (std::max(m.tool, 0) == tool)
            out.insert(m.type);
    return out;
}

std::string slice_cube(const DynamicPrintConfig &config, Print &print, Model &model)
{
    init_print({ TestMesh::cube_20x20x20 }, print, model, config);
    return Test::gcode(print);
}

std::string without_volatile_lines(const std::string &gcode)
{
    std::string        out;
    std::istringstream in(gcode);
    std::string        line;
    while (std::getline(in, line)) {
        if (line.find("; generated by") != std::string::npos || line.find("surface_filament") != std::string::npos)
            continue;
        out += line;
        out += '\n';
    }
    return out;
}

