DynamicPrintConfig two_filaments()
{
    DynamicPrintConfig config = DynamicPrintConfig::full_print_config();
    config.set_num_extruders(2);
    config.set_num_filaments(2);
    config.option<ConfigOptionFloats>("filament_diameter")->values = { 1.75, 1.75 };
    config.option<ConfigOptionFloats>("nozzle_diameter")->values   = { 0.4, 0.4 };
    config.option<ConfigOptionStrings>("filament_colour")->values  = { "#FF0000", "#00FF00" };
    config.option<ConfigOptionBool>("enable_prime_tower")->value   = true;
    config.option<ConfigOptionBool>("enable_support")->value       = false;
    config.option<ConfigOptionFloats>("wipe_tower_x")->values      = { 15. };
    config.option<ConfigOptionFloats>("wipe_tower_y")->values      = { 15. };
    config.option<ConfigOptionFloat>("prime_tower_width")->value   = 35.;
    config.set_deserialize_strict({ { "brim_type", "no_brim" }, { "skirt_loops", "0" }, { "wipe_tower_wall_type", "rectangle" },
                                    { "sparse_infill_density", "10%" } });
    return config;
}

void one_cube(Model &model)
{
    ModelObject *object = model.add_object();
    object->name        = "cube.stl";
    object->add_volume(mesh(TestMesh::cube_20x20x20));
    object->add_instance()->set_offset(Vec3d(80., 40., 0.));
    object->ensure_on_bed();
}

std::string read_file(const std::string &path)
{
    std::ifstream t(path, std::ios::binary);
    return std::string((std::istreambuf_iterator<char>(t)), std::istreambuf_iterator<char>());
}

std::string slice(const Model &model, const DynamicPrintConfig &config)
{
    Print print;
    print.apply(model, config);
    print.set_status_silent();
    print.process();
    const boost::filesystem::path path = scratch_path();
    print.export_gcode(path.string(), nullptr, nullptr);
    std::string gcode = read_file(path.string());
    boost::nowide::remove(path.string().c_str());
    return gcode;
}

// Only the line carrying the wall-clock time of the export may differ between two exports.
std::string without_timestamp(const std::string &gcode)
{
    std::istringstream in(gcode);
    std::string        line, out;
    while (std::getline(in, line))
        if (line.rfind("; generated by", 0) != 0)
            out += line + "\n";
    return out;
}

// The object's real layer tops for this config, the way the dialog will take them.
std::vector<double> layer_tops_of(const Model &model, const DynamicPrintConfig &config, double *layer_height)
{
    Print print;
    print.apply(model, config);
    REQUIRE(print.objects().size() == 1);
    const SlicingParameters sp = print.objects().front()->slicing_parameters();
    REQUIRE(sp.valid);
    *layer_height = sp.layer_height;
    const std::vector<coordf_t> profile = layer_height_profile_from_ranges(sp, t_layer_config_ranges());
    return height_pattern_layer_tops(generate_object_layers(sp, profile, false));
}

struct ToolChange
{
    double z;
    int    tool;
};

// Tool selections that change the tool, with the layer Z they happen on. The very first selection
// is the starting tool, not a change.
std::vector<ToolChange> tool_changes(const std::string &gcode)
{
    std::vector<ToolChange> out;
    std::istringstream      in(gcode);
    std::string             line;
    double                  z    = 0.;
    int                     tool = -1;
    while (std::getline(in, line)) {
        if (!line.empty() && line.back() == '\r')
            line.pop_back();
        if (line.rfind(";Z:", 0) == 0)
            z = std::atof(line.c_str() + 3);
        else if (line.rfind("; Z_HEIGHT: ", 0) == 0)
            z = std::atof(line.c_str() + 12);
        else if (line.size() >= 2 && line.size() <= 3 && line[0] == 'T' && std::isdigit((unsigned char) line[1])) {
            const int t = std::atoi(line.c_str() + 1);
            if (tool >= 0 && t != tool)
                out.push_back({ z, t });
            tool = t;
        }
    }
    return out;
}

size_t layer_count(const std::string &gcode)
{
    size_t n = 0;
    for (size_t pos = gcode.find(";LAYER_CHANGE"); pos != std::string::npos; pos = gcode.find(";LAYER_CHANGE", pos + 1))
        ++n;
    return n;
}

// Bands [4,8] and [12,16] in filament 2 on a 20 mm cube printed in filament 1.
HeightColourPattern two_band_pattern()
{
    HeightColourPattern p;
    p.start_z  = 4.;
    p.band_h   = 4.;
    p.gap_h    = 4.;
    p.repeat   = 2;
    p.sequence = { 2 };
    return p;
}

