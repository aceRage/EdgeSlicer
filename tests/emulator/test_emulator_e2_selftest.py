"""Self-test of the E2 personalities alone (no EdgeSlicer): a private emulator with an Elegoo
Centauri Carbon 1 and a Snapmaker U1 on free loopback addresses, driven the way EdgeSlicer drives
them (ElegooLink's chunked upload and SDCP websocket, SnapmakerLan's HTTP calls, U1LanRoute's MQTT
pairing), checked through emu_assert.

    python tests/emulator/test_emulator_e2_selftest.py [--work=<scratch dir>]

Exit 0 when every check passes. About 30 s.
"""
import hashlib
import json
import os
import sys
import tempfile
import time
import urllib.parse

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from emu_proc import EmulatorProcess, assert_loopback, free_port  # noqa: E402
from emu_assert import Emulator, EmuAssertionError  # noqa: E402
from proto_clients import MqttClient, WsClient, elegoo_upload, http, is_response, multipart  # noqa: E402

opts = {a.split("=")[0]: a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith("--") and "=" in a}
WORK = opts.get("--work") or tempfile.mkdtemp(prefix="emu_e2_selftest_")
CC1_HOST = assert_loopback("127.0.0.%d" % (150 + os.getpid() % 40))
U1_HOST = assert_loopback("127.0.0.%d" % (200 + os.getpid() % 40))
CC1_HTTP = free_port(CC1_HOST)
U1_PORT = free_port(U1_HOST)
PAIR_PORT, LAN_PORT = free_port(U1_HOST), free_port(U1_HOST)
CC1, U1 = "selftest-cc1", "selftest-u1"
fails, checks = [], 0


def check(cond, what):
    global checks
    checks += 1
    print(("  ok   " if cond else "  FAIL ") + what, flush=True)
    if not cond:
        fails.append(what)
    return cond


def expect(emu, pid, what, kind, mark, **fields):
    try:
        e = emu.expect(pid, kind=kind, since=mark, **fields)
        check(True, what)
        return e
    except EmuAssertionError as ex:
        check(False, "%s\n%s" % (what, ex))
        return None


GCODE = (b"; HEADER_BLOCK_START\n; generated by EdgeSlicer (selftest)\n; HEADER_BLOCK_END\nG28\n" + b"G1 X10 Y10\n" * 300 +
         b"; CONFIG_BLOCK_START\n; filament_type = PLA;PLA\n; filament_colour = #D02A2A;#F5F5F5\n; CONFIG_BLOCK_END\n")

cc1 = {"id": CC1, "personality": "elegoo_cc1", "name": "EMU selftest CC1", "bind": CC1_HOST, "port": CC1_HTTP,
       "state": "standby", "canvas": {"attached": True, "active_tray": 0},
       "slots": [{"type": "PLA", "brand": "ELEGOO", "color": "#D02A2A", "loaded": True},
                 {"type": "PLA", "name": "PLA PRO", "color": "#F5F5F5", "loaded": True, "untagged": True},
                 {"type": "ASA", "brand": "ELEGOO", "color": "#202020", "loaded": True}, {"loaded": False}],
       "camera": {"enabled": True, "viewer_limit": 4}, "faults": {}}
u1 = {"id": U1, "personality": "u1", "name": "EMU selftest U1", "bind": U1_HOST, "port": U1_PORT, "state": "standby",
      "slots": [{"type": "PLA", "color": "#D93A2B", "loaded": True}, {"type": "PLA", "color": "#F5F5F5", "loaded": True},
                {"type": "PETG", "color": "#F5F04A", "loaded": True}, {"type": "TPU", "color": "#000000", "loaded": False}],
      "u1": {"mqtt": {"enabled": True, "pairing_port": PAIR_PORT, "lan_port": LAN_PORT, "code": "12345678",
                      "auto_approve": True}}, "faults": {}}


def cc1_tests(emu):
    print("-- CC1: HTTP --")
    mark = emu.reset(CC1)
    st, body = http(CC1_HOST, CC1_HTTP, "/")
    check(st == 200 and b"ELEGOO" in body, "GET / says ELEGOO (ElegooLink's test)")
    st, _ = http(CC1_HOST, CC1_HTTP, "/api/version")
    check(st == 404, "GET /api/version is 404, so the OctoPrint test fails (%d)" % st)
    st, body = http(CC1_HOST, 3030, "/")
    check(st == 200 and b"ELEGOO" in body, "port 3030 serves the same HTTP")

    print("-- CC1: chunked upload --")
    res = elegoo_upload(CC1_HOST, CC1_HTTP, "selftest.gcode", GCODE, chunk=1500)
    check(len(res) == (len(GCODE) + 1499) // 1500 and all(s == 200 and j.get("code") == "000000" for s, j in res),
          "%d chunks, every one answered code 000000" % len(res))
    up = expect(emu, CC1, "upload logged once complete", "upload", mark, name="selftest.gcode")
    if up:
        check(up["payload"]["md5"] == hashlib.md5(GCODE).hexdigest() and up["payload"]["size"] == len(GCODE)
              and up["payload"]["chunks"] == len(res), "reassembled: size, md5 and chunk count")
        check([f["type"] for f in up["payload"].get("filaments", [])] == ["PLA", "PLA"], "the file's filaments read from its config block")
    mark = emu.mark()
    res = elegoo_upload(CC1_HOST, CC1_HTTP, "bad.gcode", GCODE, chunk=4000, md5="0" * 32)
    s, j = res[-1]
    check(s == 200 and j.get("code") != "000000" and j.get("messages"), "a wrong S-File-MD5 fails on the last chunk: %s" % j)
    expect(emu, CC1, "MD5 mismatch logged as a refused upload", "upload", mark, name="bad.gcode", refused=True)
    emu.set(CC1, {"faults": {"upload_md5_mismatch": True}})
    mark = emu.mark()
    res = elegoo_upload(CC1_HOST, CC1_HTTP, "fault.gcode", GCODE, chunk=4000)
    check(res[-1][1].get("code") != "000000", "fault upload_md5_mismatch: the right MD5 fails too")
    check("fault.gcode" not in emu.state(CC1)["files"], "nothing stored after the mismatch")
    emu.set(CC1, {"faults": {"upload_md5_mismatch": False}})

    print("-- CC1: SDCP websocket --")
    w = WsClient(CC1_HOST)
    check(w.ok, "websocket handshake on :3030/websocket (%d)" % w.status)
    w.send("ping")
    check(w.recv() == "pong", "ping -> pong")
    w.cmd(0)
    s0 = w.recv_json(want=lambda j: "Status" in j)
    check(s0["Status"]["AmsConnectStatus"] == 1 and s0["Status"]["CurrentStatus"] == [0], "Cmd 0: idle, CANVAS connected")
    w.cmd(1)
    a = w.recv_json(want=lambda j: "Attributes" in j)
    check(a["Attributes"]["BrandName"] == "ELEGOO" and a["Attributes"]["MaximumVideoStreamAllowed"] == 4
          and a["Attributes"]["MainboardID"].startswith("EMU-"), "Cmd 1: ELEGOO, 4 viewers, EMU- mainboard id")
    rid = w.cmd(324)
    ack = w.recv_json(want=is_response(324))
    payload = w.recv_json(want=is_response(324))["Data"]["Data"]
    trays = payload["canvas_list"][0]["tray_list"]
    check(ack["Data"]["Data"] == {"Ack": 0} and len(trays) == 4, "Cmd 324: Ack 0, then 4 trays")
    check(trays[1]["brand"] == "— — — —" and trays[1]["filament_code"] == "0x00000",
          "untagged tray: brand is four spaced em dashes, code 0x00000")
    check(trays[0]["status"] == 2 and trays[2]["filament_type"] == "ASA" and trays[3]["status"] == 0
          and payload["active_tray_id"] == 0, "active tray status 2, ASA in tray 2, tray 3 empty")
    emu.set(CC1, {"canvas": {"attached": False}})
    w.cmd(324)
    check(w.recv_json(want=is_response(324))["Data"]["Data"] == {"Ack": 1}, "CANVAS detached: Cmd 324 Ack 1")
    w.cmd(0)
    check(w.recv_json(want=lambda j: "Status" in j)["Status"]["AmsConnectStatus"] == 0, "CANVAS detached: AmsConnectStatus 0")
    emu.set(CC1, {"canvas": {"attached": True}})

    print("-- CC1: Cmd 128 and the slot_map --")
    for form, data in (("absent", {}), ("empty", {"slot_map": []}),
                       ("entries", {"slot_map": [{"t": 0, "canvas_id": 0, "tray_id": 0}, {"t": 1, "canvas_id": 0, "tray_id": 2}]})):
        mark = emu.reset(CC1)
        elegoo_upload(CC1_HOST, CC1_HTTP, "sm.gcode", GCODE, chunk=8000)
        body = dict({"Filename": "/local/sm.gcode", "StartLayer": 0, "Calibration_switch": 0, "PrintPlatformType": 0,
                     "Tlp_Switch": 0}, **data)
        w.cmd(128, body)
        r = w.recv_json(want=is_response(128))
        check(r["Data"]["Data"] == {"Ack": 0}, "slot_map %s: Ack 0" % form)
        e = expect(emu, CC1, "slot_map %s logged as such" % form, "start", mark, slot_map_form=form, file="sm.gcode")
        if e and form == "entries":
            check(e["payload"]["slot_map"] == data["slot_map"], "the full slot_map is in the log")
            check(any("PLA, tray 2 holds ASA" in x for x in e["payload"]["warnings"]), "T1 (PLA) -> tray 2 (ASA) flagged: %s" % e["payload"]["warnings"])
        if e and form == "empty":
            check(e["payload"]["slot_map"] == [], "slot_map [] logged as []")
        check(emu.state(CC1)["print_state"] == "printing", "printing after Ack 0 (%s)" % form)
    w.cmd(128, {"Filename": "/local/sm.gcode"})
    check(w.recv_json(want=is_response(128))["Data"]["Data"] == {"Ack": 1}, "busy: Cmd 128 Ack 1")
    emu.reset(CC1)
    w.cmd(128, {"Filename": "/local/never.gcode"})
    check(w.recv_json(want=is_response(128))["Data"]["Data"] == {"Ack": 2}, "never uploaded: Ack 2")
    emu.set(CC1, {"faults": {"refuse_start": 7}})
    elegoo_upload(CC1_HOST, CC1_HTTP, "sm.gcode", GCODE, chunk=8000)
    w.cmd(128, {"Filename": "/local/sm.gcode"})
    check(w.recv_json(want=is_response(128))["Data"]["Data"] == {"Ack": 7}, "fault refuse_start=7: Ack 7")
    emu.set(CC1, {"faults": {"refuse_start": 0}})

    print("-- CC1: pushes, camera, viewer limit --")
    emu.set_state(CC1, "printing")
    t0, pushes = time.time(), 0
    while time.time() - t0 < 3.5:
        try:
            j = w.recv_json(timeout=1, want=lambda j: "Status" in j)
            pushes += 1 if j["Status"]["PrintInfo"]["Status"] == 13 else 0
        except (TimeoutError, OSError):
            pass
    check(pushes >= 2, "status pushed while printing (%d in 3.5 s)" % pushes)
    emu.reset(CC1)
    w.cmd(386, {"Enable": 1})
    r = w.recv_json(want=is_response(386))["Data"]["Data"]
    check(r.get("Ack") == 0 and r.get("VideoUrl") == "%s:3031/video" % CC1_HOST, "Cmd 386: VideoUrl %s" % r.get("VideoUrl"))
    import socket
    s = socket.create_connection((CC1_HOST, 3031), timeout=10)
    s.sendall(("GET /video HTTP/1.1\r\nHost: %s\r\n\r\n" % CC1_HOST).encode())
    data = b""
    while data.count(b"\xff\xd9") < 1 and len(data) < 400000:
        c = s.recv(65536)
        if not c:
            break
        data += c
    s.close()
    check(b"multipart/x-mixed-replace" in data and b"\xff\xd8" in data and b"\xff\xd9" in data, "camera :3031/video streams JPEG frames")
    jpg = data[data.find(b"\xff\xd8"):data.find(b"\xff\xd9") + 2]
    check(jpg[6:10] == b"JFIF" and len(jpg) > 2000, "a real JFIF picture (%d bytes)" % len(jpg))
    others = [WsClient(CC1_HOST) for _ in range(3)]
    check(all(o.ok for o in others), "4 websocket clients in all")
    fifth = WsClient(CC1_HOST)
    check(fifth.status == 403, "the 5th is refused (403): viewer limit 4")
    for o in others + [fifth]:
        o.close()
    time.sleep(0.5)
    emu.set(CC1, {"faults": {"viewers_full": True}})
    mark = emu.mark()
    busy = WsClient(CC1_HOST)
    check(busy.status == 403, "fault viewers_full: a new handshake is refused (403)")
    busy.close()
    expect(emu, CC1, "the refusal is logged", "ws_refused", mark, fault="viewers_full")
    st, _ = http(CC1_HOST, 3031, "/video", timeout=5)
    check(st == 0, "fault viewers_full: the camera closes the viewer without an answer")
    emu.set(CC1, {"faults": {"viewers_full": False}})
    w.close()


def u1_tests(emu):
    print("-- U1: identify, probe --")
    mark = emu.reset(U1)
    st, raw = http(U1_HOST, U1_PORT, "/machine/system_info")
    pi = json.loads(raw)["result"]["system_info"]["product_info"]
    check(pi["machine_type"] == "Snapmaker U1" and pi["serial_number"].startswith("EMU-U1-"), "system_info: Snapmaker U1, EMU- serial")
    st, raw = http(U1_HOST, U1_PORT, "/printer/gcode/help")
    helps = json.loads(raw)["result"]
    check(all(k in helps for k in ("SET_PRINT_EXTRUDER_MAP", "SET_PRINT_USED_EXTRUDERS", "SET_PRINT_PREFERENCES",
                                   "INNER_FILAMENT_UNLOAD", "SM_PRINT_AUTO_FEED")), "gcode/help lists the mapping and filament macros")
    st, raw = http(U1_HOST, U1_PORT, "/printer/objects/query?print_stats&extruder&extruder1&extruder2&extruder3&print_task_config")
    s = json.loads(raw)["result"]["status"]
    ptc = s["print_task_config"]
    check(ptc["filament_type"] == ["PLA", "PLA", "PETG", ""] and ptc["filament_exist"] == [True, True, True, False]
          and ptc["filament_color_rgba"][0] == "D93A2BFF", "print_task_config: types, exist, RRGGBBAA colours")
    check(all(("extruder%s" % ("" if i == 0 else i)) in s for i in range(4)), "four extruders")
    expect(emu, U1, "the probe is logged as a probe", "probe", mark)

    print("-- U1: upload, mapped start --")
    body, ct = multipart({"print": "false", "root": "gcodes"}, "file", "u1.gcode", GCODE)
    st, _ = http(U1_HOST, U1_PORT, "/server/files/upload", "POST", body, ct)
    check(st == 201, "upload print=false (%d)" % st)
    st, raw = http(U1_HOST, U1_PORT, "/server/files/metadata?filename=u1.gcode")
    check(st == 200 and json.loads(raw)["result"]["size"] == len(GCODE), "metadata of the uploaded file")
    script = ("SET_PRINT_EXTRUDER_MAP CONFIG_EXTRUDER=0 MAP_EXTRUDER=2\nSET_PRINT_EXTRUDER_MAP CONFIG_EXTRUDER=1 MAP_EXTRUDER=0\n"
              "SET_PRINT_USED_EXTRUDERS EXTRUDERS=2,0\n"
              "SET_PRINT_PREFERENCES BED_LEVEL=0 FLOW_CALIBRATE=0 TIME_LAPSE_CAMERA=0 END_UNLOAD_FILAMENT=[1,0,1,0]")
    st, raw = http(U1_HOST, U1_PORT, "/printer/gcode/script?script=" + urllib.parse.quote(script), "POST", b"{}", "application/json")
    check(st == 200, "the mapping script runs (%d %s)" % (st, raw[:120]))
    expect(emu, U1, "extruder map 0 -> 2", "extruder_map", mark, config=0, map=2)
    expect(emu, U1, "extruder map 1 -> 0", "extruder_map", mark, config=1, map=0)
    expect(emu, U1, "used extruders [2, 0]", "used_extruders", mark, extruders=[2, 0])
    expect(emu, U1, "end unload [1,0,1,0]", "preferences", mark, end_unload_filament=[1, 0, 1, 0])
    st, raw = http(U1_HOST, U1_PORT, "/printer/objects/query?print_task_config")
    ptc = json.loads(raw)["result"]["status"]["print_task_config"]
    check(ptc["extruder_map_table"][:2] == [2, 0] and ptc["extruders_used"] == [True, False, True, False],
          "print_task_config now reports the map and the used toolheads")
    st, _ = http(U1_HOST, U1_PORT, "/printer/print/start?filename=u1.gcode", "POST", b"{}", "application/json")
    check(st == 200 and emu.state(U1)["print_state"] == "printing", "print/start -> printing")
    try:
        emu.expect_order(U1, ["upload", "extruder_map", "used_extruders", "preferences", "start"], since=mark)
        check(True, "order: upload, map, used, preferences, start")
    except EmuAssertionError as e:
        check(False, "order\n%s" % e)

    print("-- U1: refusals --")
    mark = emu.mark()
    st, raw = http(U1_HOST, U1_PORT, "/printer/gcode/script?script=" + urllib.parse.quote(
        "SET_PRINT_PREFERENCES BED_LEVEL=0 END_UNLOAD_FILAMENT=[1,0,0,0]"), "POST", b"{}", "application/json")
    check(st == 400 and b"not allowed while printing" in raw, "SET_PRINT_PREFERENCES (end unload) refused while printing (%d)" % st)
    expect(emu, U1, "the refusal is logged", "preferences", mark, refused=True)
    emu.reset(U1)
    st, _ = http(U1_HOST, U1_PORT, "/printer/print/start?filename=nope.gcode", "POST", b"{}", "application/json")
    check(st == 404, "print/start of a file never uploaded: 404")
    st, raw = http(U1_HOST, U1_PORT, "/printer/gcode/script?script=" + urllib.parse.quote(
        "SET_PRINT_EXTRUDER_MAP CONFIG_EXTRUDER=0 MAP_EXTRUDER=7"), "POST", b"{}", "application/json")
    check(st == 400, "MAP_EXTRUDER out of range refused (%d)" % st)

    print("-- U1: MQTT pairing + LAN (no cloud) --")
    mark = emu.mark()
    c = MqttClient(U1_HOST, PAIR_PORT, "edgeslicer-selftest")
    check(c.connack == 0, "pairing broker accepts any client")
    c.subscribe("12345678/config/response")
    r = c.rpc("12345678/config/request", "12345678/config/response", "server.client_manager.confirm_lan_status",
              {"clientid": "lanclient1"})
    check(r["result"]["state"] == "unauthorized", "confirm_lan_status before the request: unauthorized")
    r = c.rpc("12345678/config/request", "12345678/config/response", "server.client_manager.request_lan_auth",
              {"clientid": "lanclient1", "app_id": "edge"}, rid=2)
    check(r["result"]["state"] == "authorizing", "request_lan_auth: authorizing")
    r = c.rpc("12345678/config/request", "12345678/config/response", "server.client_manager.confirm_lan_status",
              {"clientid": "lanclient1"}, rid=3)
    check(r["result"]["state"] == "success" and r["result"]["port"] == LAN_PORT, "auto-approved: success with the LAN port")
    c.close()
    bad = MqttClient(U1_HOST, LAN_PORT, "stranger")
    check(bad.connack == 5, "LAN broker refuses an unauthorised client (CONNACK 5)")
    bad.close()
    lan = MqttClient(U1_HOST, LAN_PORT, "lanclient1")
    check(lan.connack == 0, "LAN broker admits the paired client")
    sn = r["result"]["sn"]
    lan.subscribe(sn + "/response")
    q = lan.rpc(sn + "/request", sn + "/response", "printer.objects.query", {"objects": {"print_task_config": None}}, rid=7)
    check("print_task_config" in (q.get("result") or {}).get("status", {}), "LAN JSON-RPC printer.objects.query answers")
    lan.close()
    expect(emu, U1, "pairing logged", "mqtt_pairing", mark, state="success")


def main():
    printers = [cc1, u1]
    emu_p = EmulatorProcess(os.path.join(WORK, "emuhome"), printers)
    emu_p.start()
    emu = Emulator(emu_p.control)
    try:
        cc1_tests(emu)
        u1_tests(emu)
    finally:
        emu_p.stop()
    print("\n== E2 emulator self-test: %d checks, %d failed ==" % (checks, len(fails)))
    for f in fails:
        print("  FAILED: " + f)
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
