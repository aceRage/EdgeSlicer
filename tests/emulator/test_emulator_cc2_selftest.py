def free_host(start):
    for n in range(start, start + 40):
        h = "127.0.0.%d" % n
        if safety.port_free(h, MQTT_PORT):
            return assert_loopback(h)
    raise SystemExit("no loopback address with port %d free" % MQTT_PORT)


