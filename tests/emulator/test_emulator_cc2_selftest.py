from core import safety  # noqa: E402

opts = {a.split("=")[0]: a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith("--") and "=" in a}
WORK = opts.get("--work") or tempfile.mkdtemp(prefix="emu_cc2_selftest_")
MQTT_PORT = 1883


def free_host(start):
    for n in range(start, start + 40):
        h = "127.0.0.%d" % n
        if safety.port_free(h, MQTT_PORT):
            return assert_loopback(h)
    raise SystemExit("no loopback address with port %d free" % MQTT_PORT)


COMBO_HOST = free_host(160 + os.getpid() % 20)
PLAIN_HOST = free_host(int(COMBO_HOST.rsplit(".", 1)[1]) + 1)
COMBO_HTTP, PLAIN_HTTP = free_port(COMBO_HOST), free_port(PLAIN_HOST)
COMBO, PLAIN = "selftest-cc2combo", "selftest-cc2plain"
fails, checks = [], 0


def check(cond, what):
    global checks
    checks += 1
    print(("  ok   " if cond else "  FAIL ") + what, flush=True)
    if not cond:
        fails.append(what)
    return cond


def expect(emu, pid, what, kind, mark, **fields):
    try:
        e = emu.expect(pid, kind=kind, since=mark, **fields)
        check(True, what)
        return e
    except EmuAssertionError as ex:
        check(False, "%s\n%s" % (what, ex))
        return None


GCODE = (b"; HEADER_BLOCK_START\n; generated by EdgeSlicer (selftest)\n; HEADER_BLOCK_END\nG28\n" + b"G1 X10 Y10\n" * 300 +
         b"; CONFIG_BLOCK_START\n; filament_type = PLA;PETG\n; CONFIG_BLOCK_END\n")

combo = {"id": COMBO, "personality": "elegoo_cc2", "name": "EMU selftest CC2 Combo", "bind": COMBO_HOST, "port": COMBO_HTTP,
         "state": "standby", "access_code": "123456", "canvas": {"attached": True, "active_tray": 0},
         "slots": [{"type": "PLA", "brand": "ELEGOO", "color": "#D02A2A", "loaded": True},
                   {"type": "PLA", "color": "#F5F5F5", "loaded": True},
                   {"type": "PETG", "brand": "ELEGOO", "color": "#202020", "loaded": True}, {"loaded": False}],
         "faults": {}}
plain = {"id": PLAIN, "personality": "elegoo_cc2", "name": "EMU selftest CC2", "bind": PLAIN_HOST, "port": PLAIN_HTTP,
         "state": "standby", "access_code": "4321", "canvas": {"attached": False}, "faults": {}}


def put_upload(host, port, name, data, token, chunk=1000, md5=None):
    md5 = md5 or hashlib.md5(data).hexdigest()
    out = []
    for off in range(0, len(data), chunk):
        part = data[off:off + chunk]
        st, body = http(host, port, "/upload", "PUT", part, "application/octet-stream",
                        headers={"Content-Range": "bytes %d-%d/%d" % (off, off + len(part) - 1, len(data)),
                                 "X-File-Name": name, "X-File-MD5": md5, "X-Token": token})
        try:
            out.append((st, json.loads(body)))
        except ValueError:
            out.append((st, {}))
    return out


class Cc2Mqtt:
    """EdgeSlicer's session, in Python: connect, subscribe, register, call."""

    def __init__(self, host, sn, password, cid="1_PC_7001"):
        self.sn, self.cid, self.rid = sn, cid, cid + "_req"
        self.c = MqttClient(host, MQTT_PORT, cid, user="elegoo", password=password)
        self.next_id = 500

    def register(self):
        self.c.subscribe("elegoo/%s/%s/api_response" % (self.sn, self.cid))
        self.c.subscribe("elegoo/%s/%s/register_response" % (self.sn, self.rid))
        self.c.publish("elegoo/%s/api_register" % self.sn, json.dumps({"client_id": self.cid, "request_id": self.rid}))
        topic, payload = self.c.next_message()
        return topic, json.loads(payload)

    def call(self, method, params=None):
        self.next_id += 1
        self.c.publish("elegoo/%s/%s/api_request" % (self.sn, self.cid),
                       json.dumps({"id": self.next_id, "method": method, "params": params or {}}))
        while True:
            topic, payload = self.c.next_message()
            j = json.loads(payload)
            if topic.endswith("/api_response") and j.get("id") == self.next_id:
                return j

    def close(self):
        self.c.close()


def info(host, port, token):
    st, body = http(host, port, "/system/info?X-Token=" + token, headers={"X-Token": token})
    try:
        return st, json.loads(body)
    except ValueError:
        return st, {}


def combo_tests(emu):
    print("-- CC2 Combo: HTTP --")
    mark = emu.reset(COMBO)
    st, j = info(COMBO_HOST, COMBO_HTTP, "nope")
    check(st == 401 and j.get("error_code") == 1000, "a wrong access code: HTTP 401, error_code 1000")
    st, j = info(COMBO_HOST, COMBO_HTTP, "123456")
    sn = (j.get("system_info") or {}).get("sn", "")
    check(st == 200 and j.get("error_code") == 0 and sn.startswith("EMUCC2"), "/system/info: the serial number")
    st, _ = http(COMBO_HOST, COMBO_HTTP, "/uploadFile/upload", "POST", b"x", "text/plain")
    check(st == 404, "no CC1 upload endpoint (%d)" % st)

    res = put_upload(COMBO_HOST, COMBO_HTTP, "two colour.gcode", GCODE, "123456", chunk=1000)
    check(len(res) == (len(GCODE) + 999) // 1000 and all(s == 200 and b.get("error_code") == 0 for s, b in res),
          "%d PUT chunks, each error_code 0" % len(res))
    up = expect(emu, COMBO, "upload logged once complete", "upload", mark, name="two colour.gcode")
    if up:
        check(up["payload"]["md5"] == hashlib.md5(GCODE).hexdigest() and up["payload"]["size"] == len(GCODE), "reassembled: size and md5")
    res = put_upload(COMBO_HOST, COMBO_HTTP, "bad.gcode", GCODE, "123456", chunk=4000, md5="0" * 32)
    check(res[-1][1].get("error_code") not in (None, 0), "a wrong X-File-MD5 fails on the last chunk")
    res = put_upload(COMBO_HOST, COMBO_HTTP, "x.gcode", GCODE, "nope", chunk=4000)
    check(res[0][0] == 401, "an upload with a wrong token is refused")

    print("-- CC2 Combo: MQTT --")
    bad = MqttClient(COMBO_HOST, MQTT_PORT, "1_PC_6000", user="elegoo", password="wrong")
    check(bad.connack == 4, "a wrong MQTT password: CONNACK 4 (%d)" % bad.connack)
    bad.close()
    m = Cc2Mqtt(COMBO_HOST, sn, "123456")
    check(m.c.connack == 0, "MQTT connect as elegoo / access code")
    topic, r = m.register()
    check(topic.endswith("/1_PC_7001_req/register_response") and r == {"client_id": "1_PC_7001", "error": "ok"}, "registered")
    s = m.call(1002)["result"]
    check(s["error_code"] == 0 and s["machine_status"]["status"] == 1, "1002: idle")
    c = m.call(2005)["result"]
    units = c["canvas_info"]["canvas_list"]
    check(c["error_code"] == 0 and len(units) == 1 and units[0]["connected"] == 1 and len(units[0]["tray_list"]) == 4,
          "2005: one connected CANVAS with four trays")
    check(units[0]["tray_list"][2]["filament_type"] == "PETG" and units[0]["tray_list"][3]["filament_type"] == "",
          "tray 2 PETG, tray 3 empty")

    print("-- CC2 Combo: 1020 --")
    mark = emu.mark()
    cfg = {"delay_video": False, "printer_check": True, "print_layout": "A", "bedlevel_force": False,
           "slot_map": [{"t": 0, "canvas_id": 0, "tray_id": 0}, {"t": 1, "canvas_id": 0, "tray_id": 2}]}
    r = m.call(1020, {"storage_media": "local", "filename": "nope.gcode", "config": cfg})["result"]
    check(r["error_code"] == 1021, "a file never uploaded: 1021")
    bad_map = dict(cfg, slot_map=[{"t": 0, "canvas_id": 0, "tray_id": 3}])
    r = m.call(1020, {"storage_media": "local", "filename": "two colour.gcode", "config": bad_map})["result"]
    check(r["error_code"] == 1001, "a slot_map naming the empty tray is refused (unverified on a real printer)")
    r = m.call(1020, {"storage_media": "local", "filename": "two colour.gcode", "config": cfg})["result"]
    check(r["error_code"] == 0, "the mapped start: error_code 0")
    e = expect(emu, COMBO, "the start is logged with its slot_map", "start", mark, filename="two colour.gcode", error_code=0)
    if e:
        check(e["payload"]["slot_map"] == cfg["slot_map"] and e["payload"]["print_layout"] == "A", "the full config is in the log")
    s = m.call(1002)["result"]
    check(s["machine_status"]["status"] == 2, "1002: printing")
    r = m.call(1020, {"storage_media": "local", "filename": "two colour.gcode", "config": cfg})["result"]
    check(r["error_code"] == 1009, "a second start while printing: 1009 busy")
    emu.set(COMBO, {"faults": {"too_many_clients": True}})
    m2 = Cc2Mqtt(COMBO_HOST, sn, "123456", cid="1_PC_7002")
    _t, r = m2.register()
    check(r.get("error") == "too many clients", "fault too_many_clients")
    m2.close()
    emu.set(COMBO, {"faults": {"too_many_clients": False}})
    m.close()


def plain_tests(emu):
    print("-- plain CC2 --")
    mark = emu.reset(PLAIN)
    st, j = info(PLAIN_HOST, PLAIN_HTTP, "4321")
    sn = (j.get("system_info") or {}).get("sn", "")
    check(st == 200 and sn, "a set access code answers /system/info")
    m = Cc2Mqtt(PLAIN_HOST, sn, "4321")
    check(m.register()[1].get("error") == "ok", "registered with the set access code")
    c = m.call(2005)["result"]
    check(c["error_code"] == 0 and c["canvas_info"]["canvas_list"] == [], "2005: no CANVAS, an empty canvas_list")
    put_upload(PLAIN_HOST, PLAIN_HTTP, "cube.gcode", GCODE, "4321", chunk=8000)
    r = m.call(1020, {"storage_media": "local", "filename": "cube.gcode",
                      "config": {"delay_video": False, "printer_check": False, "print_layout": "B", "bedlevel_force": False,
                                 "slot_map": []}})["result"]
    check(r["error_code"] == 0, "a single-colour start with an empty slot_map")
    expect(emu, PLAIN, "logged with an empty slot_map", "start", mark, filename="cube.gcode", slot_map=[])
    m.close()


def main():
    emu_p = EmulatorProcess(os.path.join(WORK, "emuhome"), [combo, plain])
    emu_p.start()
    emu = Emulator(emu_p.control)
    try:
        combo_tests(emu)
        plain_tests(emu)
    finally:
        emu_p.stop()
    print("\n== CC2 emulator self-test: %d checks, %d failed ==" % (checks, len(fails)))
    for f in fails:
        print("  FAILED: " + f)
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
