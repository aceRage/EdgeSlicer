boost::filesystem::path write_temp_gcode(const std::string &name, const std::string &contents)
{
    const boost::filesystem::path dir = boost::filesystem::temp_directory_path() / "edgeslicer_tests";
    boost::filesystem::create_directories(dir);
    const boost::filesystem::path path = dir / name;
    boost::nowide::ofstream ofs(path.string());
    ofs << contents;
    return path;
}

std::string thumbnail_block()
{
    return "; THUMBNAIL_BLOCK_START\n"
           "\n"
           "\n"
           "; thumbnail begin 48x48 4\n"
           "; QUJD\n"
           "; thumbnail end\n"
           "; THUMBNAIL_BLOCK_END\n";
}

std::string config_block_with_filaments(const std::string &filament_diameter)
{
    // load_from_gcode_file rejects blocks with fewer than 80 key/value pairs.
    // Repeat a known-good key so we clear that floor without round-tripping every
    // PrintConfig value (some serialize to forms that fail deserialize).
    std::ostringstream oss;
    oss << "; CONFIG_BLOCK_START\n";
    oss << "; filament_diameter = " << filament_diameter << "\n";
    for (int i = 0; i < 80; ++i)
        oss << "; layer_height = 0.2\n";
    oss << "; CONFIG_BLOCK_END\n";
    return oss.str();
}

