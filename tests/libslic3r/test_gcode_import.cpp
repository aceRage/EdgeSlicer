using Identity = std::pair<std::string, std::string>;

// C++ port of upstream Moonraker's slicer identification:
// https://github.com/Arksine/moonraker (4ba6fd228f), moonraker/components/file_manager/metadata.py,
// BaseSlicer.from_file (lines 209-224: derived classes first, then the parent), the Slic3rPE /
// Slic3r / BambuStudio identify() (lines 648-702) and PrusaSlicer.identify() (lines 431-457; the
// generic pattern is line 435).
// Returns the slicer class that would parse the file, or nullopt for UnknownSlicer, which extracts
// no thumbnails.
std::optional<Identity> moonraker_upstream_identify(const std::string &header)
{
    std::smatch m;
    if (std::regex_search(header, m, std::regex(R"(Slic3r\sPrusa\sEdition\s(.*)\son)")))
        return Identity{"Slic3r PE", m[1].str()};
    if (std::regex_search(header, m, std::regex(R"(Slic3r\s(\d.*)\son)")))
        return Identity{"Slic3r", m[1].str()};
    if (std::regex_search(header, m, std::regex(R"(; BambuStudio[^ ]* ([^\n]+))")))
        return Identity{"BambuStudio", m[1].str()};
    // PrusaSlicer.identify(): generic "; generated by X on <date> at <time>", then the alias fallback.
    if (std::regex_search(header, m, std::regex(R"(; generated by (.+?) on \d{4}-\d{2}-\d{2} at \d{2}:\d{2}:\d{2})"))) {
        const std::string full = m[1].str();
        const size_t      sp   = full.rfind(' ');
        std::string       name = sp == std::string::npos ? std::string() : full.substr(0, sp);
        const std::string ver  = sp == std::string::npos ? full : full.substr(sp + 1);
        std::string       lower = name;
        std::transform(lower.begin(), lower.end(), lower.begin(), [](unsigned char c) { return std::tolower(c); });
        // get_exclusions(): regex_id of every subclass.
        if (lower == "slic3r prusa edition" || lower == "slic3r" || lower == "bambustudio")
            return std::nullopt;
        return Identity{name, ver};
    }
    if (std::regex_search(header, m,
                          std::regex(R"((PrusaSlicer|SuperSlicer|OrcaSlicer|MomentSlicer|SliCR-3D|A3dp-Slicer|QIDISlicer)\s(.*)\son)")))
        return Identity{m[1].str(), m[2].str()};
    return std::nullopt;
}

// C++ port of Snapmaker's u1-moonraker slicer identification:
// https://github.com/Snapmaker/u1-moonraker (a308cfae31), moonraker/components/file_manager/metadata.py,
// PrusaSlicer.check_identity() (lines 407-427; the alias table is tried in this order) and
// get_slicer() (lines 1266-1281; anything unmatched is UnknownSlicer, whose parse_thumbnails
// returns None). Returns the alias, or nullopt for UnknownSlicer.
std::optional<Identity> moonraker_u1_identify(const std::string &header)
{
    static const std::vector<std::pair<std::string, std::string>> aliases = {
        {"PrusaSlicer", R"(PrusaSlicer\s(.*)\son)"},
        {"SuperSlicer", R"(SuperSlicer\s(.*)\son)"},
        {"OrcaSlicer", R"(OrcaSlicer\s(.*)\son)"},
        {"MomentSlicer", R"(MomentSlicer\s(.*)\son)"},
        {"SliCR-3D", R"(SliCR-3D\s(.*)\son)"},
        {"BambuStudio", R"(BambuStudio[^ ]*\s(.*)\n)"},
        {"A3dp-Slicer", R"(A3dp-Slicer\s(.*)\son)"},
        {"QIDISlicer", R"(QIDISlicer\s(.*)\son)"},
        {"SnapmakerOrca", R"(Snapmaker\sOrca\s(.*)\son)"},
    };
    std::smatch m;
    for (const auto &[name, expr] : aliases)
        if (std::regex_search(header, m, std::regex(expr)))
            return Identity{name, m[1].str()};
    // SUPPORTED_SLICERS continues with Slic3rPE, Slic3r, Cura, ...: none of them match an Orca-family file.
    return std::nullopt;
}

// The first lines of a real export: the generated-by line as GCode.cpp writes it, then the thumbnail block.
std::string exported_header_with_thumbnail(const std::string &producer)
{
    return "; HEADER_BLOCK_START\n; generated by " + producer + " on " + Slic3r::Utils::local_timestamp() + "\n" +
           "; HEADER_BLOCK_END\n\n" + thumbnail_block() + "G28\n";
}

